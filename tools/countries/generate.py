#!/usr/bin/env python3
"""Offline country catalogue generation/validation. Never fetch during app startup/build."""
import hashlib
import json
from pathlib import Path
import sys
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
DATA = Path(__file__).with_name('catalogue.json')
rows = json.loads(DATA.read_text())
assert len({r['code'] for r in rows}) == len(rows)
assert all(len(r['code']) == 2 and r['code'].isupper() for r in rows)
def quote(value):
    return 'null' if value is None else json.dumps(value, ensure_ascii=False).replace('$', '\\$')
entries = []
for r in rows:
    aliases = ', '.join(quote(x) for x in r['aliases'])
    entries.append(f'    CountryModel({quote(r["name"])}, {quote(r["prefix"])}, {quote(r["code"])}, {quote(r["displayName"])}, listOf({aliases}), {str(r["legacy"]).lower()}),')
kotlin = '// Generated by tools/countries/generate.py. Edit the reviewed catalogue.json snapshot.\npackage com.srisu.srisu.utils\n\ninternal fun bundledCountries(): List<CountryModel> = listOf(\n' + '\n'.join(entries) + '\n)\n'
strings = {'country_picker_title':'Country or region','country_picker_phone_title':'Calling code','country_picker_search':'Search name or code','country_picker_phone_search':'Search name or calling code','country_picker_close':'Close country picker','country_picker_clear':'Clear country search','country_picker_empty':'No matching countries','country_picker_empty_help':'Try another name or country code.','country_picker_unavailable':'No countries available','country_picker_unavailable_help':'Close this list and try opening it again.','country_picker_selected':'Selected','country_picker_choose_code':'Choose calling code','country_picker_select':'Select country or region'}
# One string-array read replaces 251 separate first-open resource reads.
country_labels = '\n'.join(f'        <item>{r["code"]}|{escape(r["displayName"])}</item>' for r in rows)
xml='<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/countries/generate.py; CLDR 48 labels, see tools/countries/README.md. -->\n<resources>\n'+'\n'.join(f'    <string name="{k}">{escape(v)}</string>' for k,v in strings.items())+'\n    <string-array name="country_labels">\n'+country_labels+'\n    </string-array>\n</resources>\n'
outputs={ROOT/'composeApp/src/commonMain/kotlin/com/srisu/srisu/utils/CountryData.kt':kotlin,ROOT/'composeApp/src/commonMain/composeResources/values/countries.xml':xml}
for path,content in outputs.items():
    if '--check' in sys.argv: assert path.read_text()==content, f'Regenerate {path}'
    else: path.parent.mkdir(parents=True,exist_ok=True); path.write_text(content)
manifest=json.loads(Path(__file__).with_name('flags-manifest.json').read_text())['flags']
for r in rows:
    code=r['code'].lower(); raw=(ROOT/f'composeApp/src/commonMain/composeResources/drawable/country_{code}.png').read_bytes()
    assert raw[:8]==b'\x89PNG\r\n\x1a\n'
    assert hashlib.sha256(raw).hexdigest()==manifest[code]['sha256'],code
print(f'{len(rows)} country records and flags verified; generated files {"checked" if "--check" in sys.argv else "updated"}.')
